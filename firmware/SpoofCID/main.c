// SpoofCIDv2 — fase 1: monitor SD bus (solo lectura)
//
// Este firmware SOLO observa el bus SD. No escribe nada en ninguna línea SD.
// El UDB detecta CMD2/CMD9 en hardware leyendo HOST_CLK (P2.2) y SD_CMD (P2.3)
// como entradas puras. La CPU lee el registro de estado del UDB y reporta
// por UART los comandos detectados.
//
// Antes de cualquier inyección de datos en el bus SD hay pasos previos
// (configurar el switch analógico externo) que no están implementados aquí.
//
// Registros UDB (sintetizados para HOST_CLK=P2[2], SD_CMD=P2[3]):
//   StatusReg   RO 0x400f0062 — bit0=cmd2, bit1=cmd9, bits[3:2]=state FSM
//   enable      WO 0x400f0070 — bit0=OVERRIDE_EN: arranca la FSM de detección
// ============================================================================

// Modo de detección: 1=interrupción HW del UDB, 0=polling
// IRQ 7 = udb_interrupt en PSoC 4; si no dispara en hardware cambiar a 0.
