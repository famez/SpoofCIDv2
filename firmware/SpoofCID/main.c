// -----------------------------------------------------------------------
// SCB0 UART — 115384 baud
// -----------------------------------------------------------------------
static void uart_init(void)
{
    PRT4_PC         = (1u << 0) | (6u << 3) | (6u << 6) | (6u << 9);
    CLK_DIVIDER_B00 = 0x80000019u;
    CLK_SELECT02    = 0x00000020u;
    SCB0_CTRL         = 0x02000007u;
    SCB0_UART_CTRL    = 0x00000000u;
    SCB0_UART_TX_CTRL = 0x00000001u;
    SCB0_TX_CTRL      = 0x80000007u;
    SCB0_TX_FIFO_CTRL = 0x00000000u;
    SCB0_CTRL        |= (1u << 31);
}

// -----------------------------------------------------------------------
// main
// -----------------------------------------------------------------------
int main(void)
{
    // P2.2 (HOST_CLK) y P2.3 (SD_CMD): entradas Hi-Z
    PRT2_PC = (1u << 6) | (1u << 9);

    udb_init();
    uart_init();

    // 2 blinks de arranque
    for (uint32_t i = 0; i < 2u; i++) {
        PRT4_DR |= LED_REQ | LED_RSP;
        volatile uint32_t d = 300000u; while (d--) {}
        PRT4_DR &= ~(LED_REQ | LED_RSP);
        d = 300000u; while (d--) {}
    }

    uart_puts("SpoofCIDv2 monitor ready\r\n");

    // Arrancar la FSM de detección del UDB (solo lectura de bus SD)
    UDB_ENABLE_REG = OVERRIDE_EN;

#if USE_UDB_IRQ
    // Habilitar IRQ del UDB StatusReg: ACTL_02 bit5 = INT_EN
    *(volatile uint8_t *)0x400f006Au |= 0x20u;
    NVIC_ICPR0 = (1u << 7);
    NVIC_ISER0 = (1u << 7);
#endif

    for (;;) {
#if USE_UDB_IRQ
        __asm volatile ("wfi");
        if (!g_udb_event) continue;
        uint8_t sta = g_udb_status;
        g_udb_event = 0u;
#else
        uint8_t sta = UDB_STATUS_REG;
        if (!(sta & 0x03u)) continue;
#endif

        if (sta & 0x01u) {
            uart_puts("CMD2 (ALL_SEND_CID)\r\n");
            PRT4_DR |= LED_REQ;
            // Esperar a que el UDB vuelva a IDLE (cmd2 se limpia)
            do { sta = UDB_STATUS_REG; } while (sta & 0x01u);
            PRT4_DR &= ~LED_REQ;
        }

        if (sta & 0x02u) {
            uart_puts("CMD9 (SEND_CSD)\r\n");
            PRT4_DR |= LED_RSP;
            do { sta = UDB_STATUS_REG; } while (sta & 0x02u);
            PRT4_DR &= ~LED_RSP;
        }
    }
}
