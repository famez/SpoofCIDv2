//
// Los blobs configuran el fabric para que el UDB pueda LEER HOST_CLK (P2.2)
// y SD_CMD (P2.3). Todos los Port Adapters de salida (PA0, PA1, PA2, PA3)
// se dejan a cero: el UDB no puede conducir ningún pin físico.
// -----------------------------------------------------------------------
static void memcpy8(volatile uint8_t *dst, const uint8_t *src, uint32_t n)
{
    while (n--) *dst++ = *src++;
}

