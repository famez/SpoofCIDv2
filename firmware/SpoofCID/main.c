// -----------------------------------------------------------------------
// UART helpers
// -----------------------------------------------------------------------
static void uart_putc(uint8_t c)
{
    uint32_t t = 200000u;
    while ((SCB0_TX_FIFO_STATUS & 0x1Fu) >= 8u && --t) {}
    SCB0_TX_FIFO_WR = c;
}

static void uart_puts(const char *s)
{
    while (*s) uart_putc((uint8_t)*s++);
}

